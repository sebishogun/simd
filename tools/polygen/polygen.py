#!/usr/bin/env python3
"""Generate the minimax polynomial coefficients used by csrc/math.c.

Why this exists
---------------
A vectorized transcendental is a range reduction followed by a polynomial.
The polynomial has to be a genuine minimax fit over the reduced interval: a
truncated Taylor series is correct at one point and drifts away from it, and
by the end of the interval it costs several ULP that a fit of the same degree
would not.

The coefficients could have been copied from SLEEF, which is what the plan
originally proposed. Computing them here instead keeps the repository free of
another project's license and, more usefully, makes them reproducible: if an
interval or a degree changes this regenerates the numbers, rather than leaving
them to be hand-edited, which is exactly where a wrong digit would hide.

Every fit is in u = x^2 where the function allows it. sin, atan and the log
series are odd and cos is even, so a fit in x would spend half its degrees
proving that the coefficients it already knows to be zero really are zero.
Fitting in u costs half the terms for the same accuracy, and it also keeps the
symmetry exact — sin(-x) is the negation of sin(x) bit for bit, which no
amount of accuracy would give back once even-order terms crept in.

The output is committed, so building the library needs no Python. Run this
only when changing a polynomial:

    python3 tools/polygen/polygen.py > csrc/poly.h
"""

import struct
import sys

from mpmath import mp, mpf

mp.prec = 250


def remez(f, lo, hi, degree, iters=80):
    """Minimax coefficients of a degree-`degree` polynomial for f on [lo, hi].

    A straight Remez exchange. The returned error is measured on a fine sweep
    rather than taken from the solve, so it reflects the polynomial that is
    actually emitted.
    """
    n = degree + 1
    nodes = sorted(
        (lo + hi) / 2 + (hi - lo) / 2 * mp.cos(mp.pi * mpf(i) / n) for i in range(n + 1)
    )

    coeffs = [mpf(0)] * n
    for _ in range(iters):
        A = mp.matrix(n + 1, n + 1)
        b = mp.matrix(n + 1, 1)
        for i, x in enumerate(nodes):
            for j in range(n):
                A[i, j] = x**j
            A[i, n] = mpf(-1) ** i
            b[i] = f(x)
        sol = mp.lu_solve(A, b)
        coeffs = [sol[j] for j in range(n)]

        def err(x):
            return sum(c * x**j for j, c in enumerate(coeffs)) - f(x)

        # Move each node to the extremum of the error in its own subinterval.
        # A dense scan is enough at this precision and needs no derivative.
        edges = [lo] + [(nodes[i] + nodes[i + 1]) / 2 for i in range(n)] + [hi]
        moved = []
        for i in range(n + 1):
            a, c = edges[i], edges[i + 1]
            sign = 1 if err((a + c) / 2) > 0 else -1
            best, bx = None, a
            for k in range(301):
                x = a + (c - a) * mpf(k) / 300
                v = sign * err(x)
                if best is None or v > best:
                    best, bx = v, x
            moved.append(bx)
        if max(abs(p - q) for p, q in zip(moved, nodes)) < (hi - lo) * mpf(10) ** -30:
            nodes = moved
            break
        nodes = sorted(moved)

    def approx(x):
        return sum(c * x**j for j, c in enumerate(coeffs))

    worst = max(
        abs(approx(lo + (hi - lo) * mpf(i) / 8000) - f(lo + (hi - lo) * mpf(i) / 8000))
        for i in range(8001)
    )
    return coeffs, worst


def as_c(x, single):
    """A C99 hex float literal, which the parser reads back exactly.

    Decimal would need seventeen significant digits to round-trip a double and
    would still leave a reader wondering whether it did. Hex cannot lose a bit.
    """
    v = float(x)
    if single:
        v = struct.unpack("f", struct.pack("f", v))[0]
        return float.hex(v) + "f"
    return float.hex(v)


def emit(name, coeffs, worst, single, comment):
    suffix = "F" if single else ""
    print(f"// {comment}")
    print(f"//   worst error over the interval: {mp.nstr(worst, 4)}")
    for i, c in enumerate(coeffs):
        print(f"#define {name}{suffix}_{i} {as_c(c, single)}")
    print()


def fit(name, f, lo, hi, deg64, deg32, comment):
    """Emit both precisions of one fit."""
    for single, deg in ((False, deg64), (True, deg32)):
        coeffs, worst = remez(f, lo, hi, deg)
        emit(name, coeffs, worst, single, f"{comment}, degree {deg}")
        print(f"// (progress: {name} {'f32' if single else 'f64'} done)", file=sys.stderr)


def main():
    print("// Code generated by tools/polygen/polygen.py. DO NOT EDIT.")
    print("//")
    print("// Minimax coefficients for csrc/math.c. Each is a C99 hex float, which")
    print("// the parser reads back exactly. See the generator for how the interval")
    print("// and degree of each fit were chosen; in short, every one is a fit in")
    print("// u = x^2 wherever the function's parity allows it, which halves the")
    print("// term count and keeps the symmetry exact.")
    print()
    print("#ifndef SIMD_POLY_H")
    print("#define SIMD_POLY_H")
    print()

    ln2 = mp.log(2)

    # 2^r for r in [-1/2, 1/2]. Reducing against 2^k rather than e^k makes the
    # scale step exact: k is an integer and 2^k is one exponent field.
    fit(
        "EXP2P",
        lambda x: mp.power(2, x),
        mpf("-0.5"),
        mpf("0.5"),
        13,
        7,
        "2^r on [-1/2, 1/2]",
    )

    # e^r for |r| <= ln2/2. exp reduces against ln2 in its own domain rather
    # than computing 2^(x*log2e), because the product loses bits exactly where
    # it matters: at x=700 an ulp of x*log2e is 1.1e-13, which is 340 ULP of
    # the answer. Cody-Waite subtraction of a split ln2 keeps the reduced
    # argument accurate, and that needs a fit of e^r rather than 2^r.
    fit("EXPP", mp.exp, -ln2 / 2, ln2 / 2, 12, 6, "e^r on |r|<=ln2/2")

    # log2. The mantissa is reduced to [sqrt(2)/2, sqrt(2)) and the fit is in
    # s = (m-1)/(m+1), whose series is odd, so this fits log2((1+s)/(1-s))/s
    # as a polynomial in u = s^2.
    smax = (mp.sqrt(2) - 1) / (mp.sqrt(2) + 1)
    fit(
        "LOG2P",
        lambda u: (mp.log((1 + mp.sqrt(u)) / (1 - mp.sqrt(u))) / ln2 / mp.sqrt(u))
        if u > 0
        else mpf(2) / ln2,
        mpf(0),
        smax**2,
        7,
        4,
        "log2((1+s)/(1-s))/s in u=s^2",
    )

    # sin and cos, reduced to |r| <= pi/4.
    q = (mp.pi / 4) ** 2
    fit(
        "SINP",
        lambda u: (mp.sin(mp.sqrt(u)) / mp.sqrt(u)) if u > 0 else mpf(1),
        mpf(0),
        q,
        7,
        3,
        "sin(r)/r in u=r^2, |r|<=pi/4",
    )
    fit("COSP", lambda u: mp.cos(mp.sqrt(u)), mpf(0), q, 8, 4, "cos(r) in u=r^2, |r|<=pi/4")

    # atan, reduced to |r| <= tan(pi/12) by two identities.
    tmax = mp.tan(mp.pi / 12)
    fit(
        "ATANP",
        lambda u: (mp.atan(mp.sqrt(u)) / mp.sqrt(u)) if u > 0 else mpf(1),
        mpf(0),
        tmax**2,
        9,
        4,
        "atan(r)/r in u=r^2, |r|<=tan(pi/12)",
    )

    # asin on [0, 1/2]; above that the identity asin(x) = pi/2 - 2*asin(sqrt((1-x)/2))
    # brings the argument back into range.
    fit(
        "ASINP",
        lambda u: ((mp.asin(mp.sqrt(u)) - mp.sqrt(u)) / mp.sqrt(u) ** 3)
        if u > 0
        else mpf(1) / 6,
        mpf(0),
        mpf("0.25"),
        14,
        4,
        "(asin(s)-s)/s^3 in u=s^2, s in [0,1/2]",
    )

    # A cbrt seed on [1, 8). Two Newton steps follow, each of which triples the
    # correct digits, so a short fit is enough and a long one would be waste.
    fit("CBRTP", mp.cbrt, mpf(1), mpf(8), 5, 4, "cbrt seed on [1,8)")

    print("#endif  // SIMD_POLY_H")


if __name__ == "__main__":
    main()
