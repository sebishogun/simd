// This file renders the two generated halves of the per-operation dispatch:
//
//   - RootDispatch: one file in the root package per architecture, holding a
//     static tier-indexed table per flat-group operation and a static partial
//     Ops struct per (element type, tier). Every entry is a plain identifier
//     -- an exported guard, or an instantiated ref function -- because any
//     computed entry would force an init function, and anything reachable
//     from init is alive in every binary that imports the package. Static
//     tables are what let the linker drop every operation a program never
//     calls, which is the entire point.
//
//   - ArchSets: one file in internal/<arch>, assembling whole kernel.Sets on
//     demand for the conformance and coverage machinery. Only tests call it,
//     so none of it reaches a consumer's binary.
//
// The flat groups (Bytes, Convert, Mask) get one table per operation: that is
// where a consumer like simdjson uses seventeen operations out of hundreds,
// and per-operation granularity is the difference between linking those
// seventeen and linking the group. The numeric groups get one partial struct
// per (type, tier), overlaid onto the reference set lazily by the dispatcher:
// their reference fallbacks are built by generic constructors whose fields
// cannot be named in a static literal, and per-type granularity is already
// what their callers see through the ops[T] type switch.

// flatGroups are the kernel.Set groups that get per-operation tables.
var flatGroups = map[string]bool{"Bytes": true, "Convert": true, "Mask": true}

// TableName is the root-package table variable for a flat-group operation.
func TableName(k spec.Kernel) string {
	return "tbl" + k.Group + k.Field
}

// opsVarName is the root-package partial Ops variable for a numeric group and
// tier ("opsF32SSE2").
func opsVarName(group, tierSuffix string) string {
	return "ops" + group + tierSuffix
}

// sigTypes renders a types-only func signature for a kernel's public shape.
func sigTypes(k spec.Kernel) string {
	parts := make([]string, len(k.Params))
	for i, p := range k.Params {
		parts[i] = p.Type.GoString()
	}
	sig := "func(" + strings.Join(parts, ", ") + ")"
	if k.Result != nil && k.Result2 != nil {
		sig += fmt.Sprintf(" (%s, %s)", k.Result.Type.GoString(), k.Result2.Type.GoString())
	} else if k.Result != nil {
		sig += " " + k.Result.Type.GoString()
	}
	return sig
}

// numericElem maps a numeric group name to its Go element type.
var numericElem = map[string]string{
	"F32": "float32", "F64": "float64",
	"I8": "int8", "I16": "int16", "I32": "int32", "I64": "int64",
	"U8": "uint8", "U16": "uint16", "U32": "uint32", "U64": "uint64",
}

// RootDispatch renders the per-arch dispatch tables file for the root
// package.
//
// tiers is the architecture's accelerated tier order, matching the runtime's
// index choice; slot 0 is always the portable reference. present[tier] holds
// the kernels that were actually emitted for that tier -- a kernel the
// generator declined keeps its reference entry, exactly as the registry
// used to fall back.
func RootDispatch(arch string, tiers []string, present map[string]map[string]bool,
	all []spec.Kernel, prov Provenance) string {

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by simdgen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Per-operation dispatch tables for %s: static composite literals of\n", arch)
	fmt.Fprintf(&b, "// exported guards and reference functions, one table per flat-group\n")
	fmt.Fprintf(&b, "// operation and one partial Ops struct per (type, tier). Static is the\n")
	fmt.Fprintf(&b, "// contract: an init function here would defeat the linker's dead-code\n")
	fmt.Fprintf(&b, "// elimination for every consumer at once.\n\n")
	fmt.Fprintf(&b, "//go:build %s && !purego\n\n", arch)
	fmt.Fprintf(&b, "package simd\n\n")
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t%q\n", "github.com/sebishogun/simd/internal/"+arch)
	fmt.Fprintf(&b, "\t%q\n", "github.com/sebishogun/simd/internal/kernel")
	fmt.Fprintf(&b, "\t%q\n)\n\n", "github.com/sebishogun/simd/internal/ref")

	fmt.Fprintf(&b, "// dispatchTiers is the tier order the runtime indexes into; slot 0 is\n")
	fmt.Fprintf(&b, "// the portable reference.\n")
	fmt.Fprintf(&b, "var dispatchTiers = [...]string{%q", "scalar")
	for _, t := range tiers {
		fmt.Fprintf(&b, ", %q", t)
	}
	fmt.Fprintf(&b, "}\n\n")

	// Flat groups: one table per operation.
	for _, k := range all {
		if !flatGroups[k.Group] {
			continue
		}
		fmt.Fprintf(&b, "var %s = [...]%s{\n\tref.%s,\n", TableName(k), sigTypes(k), k.RefFunc)
		for _, t := range tiers {
			if present[t][k.CName] {
				fmt.Fprintf(&b, "\t%s.%s%s,\n", arch, exportedGuard(k), strings.ToUpper(t))
			} else {
				fmt.Fprintf(&b, "\tref.%s,\n", k.RefFunc)
			}
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	// Numeric groups: one partial Ops struct per (group, tier), then the
	// tier-indexed pointer array the dispatcher overlays from. Slot 0 is nil:
	// the reference base needs no overlay.
	groups := numericGroupsIn(all)
	for _, g := range groups {
		elem := numericElem[g]
		for _, t := range tiers {
			suffix := strings.ToUpper(t)
			fmt.Fprintf(&b, "var %s = kernel.Ops[%s]{\n", opsVarName(g, suffix), elem)
			for _, k := range all {
				if k.Group != g || !present[t][k.CName] {
					continue
				}
				fmt.Fprintf(&b, "\t%s: %s.%s%s,\n", k.Field, arch, exportedGuard(k), strings.ToUpper(t))
			}
			fmt.Fprintf(&b, "}\n\n")
		}
		fmt.Fprintf(&b, "var ops%sByTier = [...]*kernel.Ops[%s]{\n\tnil,\n", g, elem)
		for _, t := range tiers {
			fmt.Fprintf(&b, "\t&%s,\n", opsVarName(g, strings.ToUpper(t)))
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	out := b.String()
	if formatted, err := format.Source([]byte(out)); err == nil {
		return string(formatted)
	}
	return out
}

// exportedGuard mirrors guardName: the exported threshold wrapper.
func exportedGuard(k spec.Kernel) string {
	return strings.ToUpper(k.GoName[:1]) + k.GoName[1:]
}

func numericGroupsIn(all []spec.Kernel) []string {
	seen := map[string]bool{}
	for _, k := range all {
		if _, ok := numericElem[k.Group]; ok {
			seen[k.Group] = true
		}
	}
	out := make([]string, 0, len(seen))
	for g := range seen {
		out = append(out, g)
	}
	sort.Strings(out)
	return out
}

// RootDispatchFallback renders the dispatch file for purego builds and for
// architectures with no generated backend: every table is one reference slot.
func RootDispatchFallback(arches []string, all []spec.Kernel, prov Provenance) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by simdgen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// The reference-only dispatch: purego builds, and every architecture\n")
	fmt.Fprintf(&b, "// without a generated backend.\n\n")
	var neg []string
	for _, a := range arches {
		neg = append(neg, "!"+a)
	}
	fmt.Fprintf(&b, "//go:build purego || (%s)\n\n", strings.Join(neg, " && "))
	fmt.Fprintf(&b, "package simd\n\n")
	fmt.Fprintf(&b, "import (\n\t%q\n\t%q\n)\n\n",
		"github.com/sebishogun/simd/internal/kernel",
		"github.com/sebishogun/simd/internal/ref")
	fmt.Fprintf(&b, "var dispatchTiers = [...]string{%q}\n\n", "scalar")

	for _, k := range all {
		if !flatGroups[k.Group] {
			continue
		}
		fmt.Fprintf(&b, "var %s = [...]%s{ref.%s}\n", TableName(k), sigTypes(k), k.RefFunc)
	}
	fmt.Fprintf(&b, "\n")
	for _, g := range numericGroupsIn(all) {
		fmt.Fprintf(&b, "var ops%sByTier = [...]*kernel.Ops[%s]{nil}\n", g, numericElem[g])
	}

	out := b.String()
	if formatted, err := format.Source([]byte(out)); err == nil {
		return string(formatted)
	}
	return out
}

// ArchSets renders the internal/<arch> aggregator that assembles whole
// kernel.Sets for the conformance and coverage tests. It is the only caller
// of the per-file register functions, and nothing in a consumer's binary
// references it.
func ArchSets(arch string, tiers []string, regFuncs map[string][]string, prov Provenance) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by simdgen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Whole-set assembly for the conformance and coverage machinery. Tests\n")
	fmt.Fprintf(&b, "// call this; consumers never do, so none of it is linked into their\n")
	fmt.Fprintf(&b, "// binaries and the per-operation dispatch tables keep their dead-code\n")
	fmt.Fprintf(&b, "// elimination.\n\n")
	fmt.Fprintf(&b, "//go:build %s && !purego\n\n", arch)
	fmt.Fprintf(&b, "package %s\n\n", arch)
	fmt.Fprintf(&b, "import (\n\t%q\n\t%q\n)\n\n",
		"github.com/sebishogun/simd/internal/kernel",
		"github.com/sebishogun/simd/internal/ref")

	fmt.Fprintf(&b, "// Sets returns every tier's complete kernel set, the reference standing\n")
	fmt.Fprintf(&b, "// in for anything not generated, in accelerated-tier order.\n")
	fmt.Fprintf(&b, "func Sets() map[string]kernel.Set {\n")
	fmt.Fprintf(&b, "\tout := map[string]kernel.Set{}\n")
	for _, t := range tiers {
		fmt.Fprintf(&b, "\t{\n\t\ts := ref.Set()\n\t\ts.Name = %q\n", t)
		for _, fn := range regFuncs[t] {
			fmt.Fprintf(&b, "\t\t%s(&s)\n", fn)
		}
		fmt.Fprintf(&b, "\t\tref.FillFastFallbacks(&s)\n")
		fmt.Fprintf(&b, "\t\tout[%q] = s\n\t}\n", t)
	}
	fmt.Fprintf(&b, "\treturn out\n}\n\n")

	fmt.Fprintf(&b, "// TierOrder is the accelerated tier order Sets covers.\n")
	fmt.Fprintf(&b, "var TierOrder = [...]string{")
	for i, t := range tiers {
		if i > 0 {
			fmt.Fprintf(&b, ", ")
		}
		fmt.Fprintf(&b, "%q", t)
	}
	fmt.Fprintf(&b, "}\n")

	out := b.String()
	if formatted, err := format.Source([]byte(out)); err == nil {
		return string(formatted)
	}
	return out
}

// RootDispatchTest renders a _test.go companion enumerating every flat-group
// table and exposing the arch's Sets constructor, so the completeness and
// inventory tests can walk the real runtime surface. A test file is the one
// place such an enumeration is allowed to exist: a non-test map referencing
// every table would resurrect exactly the liveness the tables eliminate.
func RootDispatchTest(arch string, tiers []string, all []spec.Kernel, prov Provenance) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by simdgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "//go:build %s && !purego\n\n", arch)
	fmt.Fprintf(&b, "package simd\n\n")
	fmt.Fprintf(&b, "import (\n\t%q\n\t%q\n)\n\n",
		"github.com/sebishogun/simd/internal/"+arch,
		"github.com/sebishogun/simd/internal/kernel")

	fmt.Fprintf(&b, "// allFlatTables enumerates every per-operation dispatch table, keyed\n")
	fmt.Fprintf(&b, "// Group.Field, each entry one tier slot as an untyped value.\n")
	fmt.Fprintf(&b, "var allFlatTables = map[string][]any{\n")
	for _, k := range all {
		if !flatGroups[k.Group] {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {", k.Group+"."+k.Field)
		for i := 0; i <= len(tiers); i++ {
			if i > 0 {
				fmt.Fprintf(&b, ", ")
			}
			fmt.Fprintf(&b, "%s[%d]", TableName(k), i)
		}
		fmt.Fprintf(&b, "},\n")
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// archSets hands the tests every tier's complete kernel set.\n")
	fmt.Fprintf(&b, "var archSets func() map[string]kernel.Set = %s.Sets\n", arch)

	out := b.String()
	if formatted, err := format.Source([]byte(out)); err == nil {
		return string(formatted)
	}
	return out
}

