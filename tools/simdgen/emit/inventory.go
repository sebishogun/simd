package emit

import (
	"fmt"
	"sort"
	"strings"

	"github.com/sebishogun/simd/tools/simdgen/spec"
)

// Inventory renders the manifest as data the main module can assert against.
//
// The hole it closes is the one that produced the -tags purego panic:
// IndexNonASCII was registered for every generated backend and not for the
// portable one, so every accelerated tier passed and the one configuration
// guaranteed to build everywhere panicked at the first call.
// TestDispatchTableComplete was written for that, and it can only check the
// groups where every field applies to every caller — Bytes, Convert, Mask and
// the two complex ones. The number groups are one struct per element type, so
// U8.Sqrt is legitimately nil and always will be, and a blanket non-nil check
// over them would report five hundred holes that are not holes.
//
// The manifest is the only thing that knows which of those nils are real. If
// it declares a kernel with Group "F32" and Field "ShiftDiv", then
// active.F32.ShiftDiv must be non-nil on every tier and ref.Set().F32.ShiftDiv
// must be non-nil too, whatever U8 does. Emitting the declarations as data is
// what lets a test say that.
//
// This is deliberately NOT a generated kernel.Ops or ref table. Those carry
// the numerical contract in their doc comments — which rule an operation falls
// under, what it promises for NaN and signed zero — and generating them would
// replace the most useful prose in the repository with a list.
func Inventory(kernels []spec.Kernel, prov Provenance) string {
	type decl struct{ group, field, ref, cname string }

	// One entry per (group, field). A field is usually declared once, but the
	// same Field can legitimately appear for several element types, and for
	// those the group differs so the pair is still unique.
	seen := map[string]decl{}
	for _, k := range kernels {
		key := k.Group + "." + k.Field
		if _, ok := seen[key]; !ok {
			seen[key] = decl{k.Group, k.Field, k.RefFunc, k.CName}
		}
	}
	keys := make([]string, 0, len(seen))
	for k := range seen {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("// Code generated by simdgen. DO NOT EDIT.\n")
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// Source:  the kernel manifest, tools/simdgen/kernels\n")
	fmt.Fprintf(&b, "// Command: %s\n", prov.Command)
	b.WriteString("\npackage backend\n\n")
	b.WriteString(`// Declared is one kernel the manifest declares: the dispatch group it
// belongs to, the field inside that group, and the name of the portable
// implementation the generated guard falls back to below its threshold.
type Declared struct {
	Group   string
	Field   string
	RefFunc string
	CName   string
}

// Inventory is every kernel the manifest declares, sorted, one entry per
// group and field.
//
// It exists so a test can assert that each declared slot is actually filled —
// in the assembled dispatch table AND in the reference set, which is where the
// hole that panicked under -tags purego was. A kernel can be declared here and
// still be absent from a given tier: the generator drops what a target cannot
// support, and the dispatcher fills the slot from the reference. What may not
// happen is the slot being empty in both.
var Inventory = []Declared{
`)
	for _, k := range keys {
		d := seen[k]
		fmt.Fprintf(&b, "\t{%q, %q, %q, %q},\n", d.group, d.field, d.ref, d.cname)
	}
	b.WriteString("}\n")
	return b.String()
}
