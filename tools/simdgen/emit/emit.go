// Package emit writes Plan 9 assembly and the matching Go declarations.
//
// # What the emitted file looks like
//
//	TEXT ·addFloat32Neon(SB), NOSPLIT|NOFRAME, $0-72
//	    MOVD dst_base+0(FP),  R0     // the ABI bridge: Go's stack frame
//	    MOVD a_base+24(FP),   R1     // to the C argument registers the
//	    MOVD b_base+48(FP),   R2     // compiled body expects
//	    MOVD dst_len+8(FP),   R3
//	    WORD $0x2518e3e0             // ptrue p0.s
//	    WORD $0xa540a020             // ld1w  {z0.s}, p0/z, [x1]
//	    ...
//	    RET
//
// The body is the compiled function's bytes, verbatim. Nothing is decoded or
// re-spelled, because nothing needs to be: a function's internal branches are
// PC-relative and stay correct as long as the blob moves as a unit.
//
// That is also what makes SVE reachable. Go's assembler cannot spell a single
// SVE instruction — it has no Z or P registers at all — but WORD emits a raw
// 32-bit encoding, and the assembler does not need to understand it.
package emit

import (
	"errors"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/sebishogun/simd/tools/simdgen/objfile"
	"github.com/sebishogun/simd/tools/simdgen/spec"
	"github.com/sebishogun/simd/tools/simdgen/target"
)

// Instr is one disassembled instruction, as far as this package needs it.
type Instr struct {
	Offset   uint64
	Mnemonic string
}

// Provenance records how a file was produced, so a reader can reproduce it.
type Provenance struct {
	ClangVersion string
	Command      string
	Source       string
	// Stem is the source file's basename without extension ("bytes"), used
	// to name the per-file registration function.
	Stem string
}

// Frame is the computed Go ABI0 argument frame for a kernel.
type Frame struct {
	// Offsets maps "param" or "param_base"/"param_len"/"param_cap" to its
	// byte offset from FP.
	Offsets map[string]int
	// ResultOff is the offset of the result, or -1 if there is none.
	ResultOff int
	// ResultOff2 is the offset of the second result, or -1. See spec.Result2.
	ResultOff2 int
	// Size is the total argument-plus-result frame size, which is the N in
	// the TEXT directive's $0-N.
	Size int
}

// LayoutFrame computes the Go ABI0 argument frame.
//
// ABI0 is the stack-based convention: every argument and result lives in the
// caller's frame at an FP-relative offset, laid out in declaration order with
// natural alignment. Getting an offset wrong here produces a kernel that reads
// the wrong memory, which is why `go vet`'s asmdecl check exists and why the
// generated declaration is emitted from this same layout.
func LayoutFrame(k spec.Kernel) Frame {
	f := Frame{Offsets: map[string]int{}, ResultOff: -1, ResultOff2: -1}
	off := 0
	align := func(a int) {
		if r := off % a; r != 0 {
			off += a - r
		}
	}
	for _, p := range k.Params {
		align(p.Type.Align())
		if p.Type.IsSlice() {
			f.Offsets[p.Name+"_base"] = off
			f.Offsets[p.Name+"_len"] = off + 8
			f.Offsets[p.Name+"_cap"] = off + 16
			off += 24
			continue
		}
		f.Offsets[p.Name] = off
		off += p.Type.Size()
	}
	if k.Result != nil {
		// The results section starts on a word boundary, whatever the result's
		// own alignment is, and then the result sits at its natural alignment
		// within it. The total is not rounded up afterwards.
		//
		// Both halves of that matter and neither is guessable. For
		// func([]float32) float32 the arguments end at 24, which is already
		// aligned, so the result goes at 24 and the frame is 28 — not 32. For
		// func([]float32, float32) float32 the arguments end at 28, so the
		// result is pushed to 32 and the frame is 36 — not 32. Getting either
		// wrong makes the kernel read or write the wrong stack slot, which is
		// why `go vet` checks it and why it is worth running.
		align(8)
		f.ResultOff = off
		off += k.Result.Type.Size()
		if k.Result2 != nil {
			// The second result follows at its own natural alignment inside
			// the results section, which has already been word-aligned.
			align(k.Result2.Type.Align())
			f.ResultOff2 = off
			off += k.Result2.Type.Size()
		}
	}
	f.Size = off
	return f
}

// Asm renders the Plan 9 assembly file for one target.
func Asm(kernels []spec.Kernel, fns map[string]*objfile.Func, disasm map[string][]Instr, tgt target.Target, prov Provenance) (string, error) {
	var b strings.Builder

	fmt.Fprintf(&b, "// Code generated by simdgen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Source:  %s\n", prov.Source)
	fmt.Fprintf(&b, "// Target:  %s\n", tgt)
	fmt.Fprintf(&b, "// Clang:   %s\n", prov.ClangVersion)
	fmt.Fprintf(&b, "// Command: %s\n//\n", prov.Command)
	fmt.Fprintf(&b, "// The instruction bytes below are the compiled function verbatim. Branches\n")
	fmt.Fprintf(&b, "// inside a function are PC-relative and remain correct because the whole\n")
	fmt.Fprintf(&b, "// body moves as a unit.\n\n")
	fmt.Fprintf(&b, "//go:build %s\n\n", tgt.BuildTag())
	fmt.Fprintf(&b, "#include \"textflag.h\"\n")
	// funcdata.h is needed only where a kernel has a real frame, which is the
	// trampoline case. A framed assembly function that the garbage collector
	// might have to walk needs to say whether its locals hold pointers; without
	// it the runtime aborts with "missing stackmap" the first time the
	// goroutine stack grows underneath one.
	if tgt.SaveArea > 0 {
		fmt.Fprintf(&b, "#include \"funcdata.h\"\n")
	}
	b.WriteString("\n")

	names := make([]string, 0, len(kernels))
	for _, k := range kernels {
		names = append(names, k.GoName)
	}
	sort.Strings(names)

	// Constant pools are emitted once per file and shared, since two kernels
	// compiled from the same translation unit often reference the same one.
	pools := newPoolSet()

	for _, k := range kernels {
		fn, ok := fns[k.CName]
		if !ok {
			return "", fmt.Errorf("emit: no compiled function for %s", k.CName)
		}
		if err := emitFunc(&b, k, fn, disasm[k.CName], tgt, pools); err != nil {
			return "", err
		}
	}

	if s := pools.render(); s != "" {
		b.WriteString("\n// Constant pools lifted out of the compiled object. RODATA|NOPTR tells the\n")
		b.WriteString("// garbage collector these hold no pointers and must not be written.\n")
		b.WriteString(s)
	}
	return b.String(), nil
}

func emitFunc(b *strings.Builder, k spec.Kernel, fn *objfile.Func, instrs []Instr, tgt target.Target, pools *poolSet) error {
	frame := LayoutFrame(k)

	fmt.Fprintf(b, "// func %s(%s)%s\n", k.GoName, goParams(k), goResult(k))

	// Where the C ABI expects its caller to have provided a register save
	// area, the kernel is emitted as two symbols and the compiled body is
	// called rather than fallen into. See target.SaveArea and the comment on
	// emitTrampoline.
	if tgt.SaveArea > 0 {
		return emitTrampoline(b, k, fn, instrs, tgt, pools, frame)
	}

	fmt.Fprintf(b, "TEXT ·%s(SB), NOSPLIT|NOFRAME, $0-%d\n", k.GoName, frame.Size)

	prologue, err := prologueFor(k, frame, tgt)
	if err != nil {
		return err
	}
	for _, line := range prologue {
		fmt.Fprintf(b, "\t%s\n", line)
	}

	if err := emitRelocated(b, fn, instrs, tgt, pools, k.GoName); err != nil {
		return err
	}

	// Nothing is appended after the body, unless the target says otherwise.
	// The compiled function ends with its own return, and LLVM lays basic
	// blocks out after that return — the AVX2 dot product has a jmp past it —
	// so there is no position after the body that is guaranteed to execute. A
	// kernel with a result therefore writes through a pointer to the frame
	// slot instead of returning in a register; see spec.ResultAddr.
	//
	// The one exception is ppc64le, where the body's returns have been
	// rewritten into branches to exactly here so that this epilogue can put
	// r0 back; see returns_ppc64.go. On every other target the list is empty
	// and the trailing RET is unreachable, existing only so the assembler
	// sees a terminated function.
	emitEpilogue(b, tgt)
	b.WriteString("\tRET\n\n")
	return nil
}

// emitEpilogue writes the instructions that must run on the way out, which
// only reach control because retargetReturns pointed the body's returns here.
func emitEpilogue(b *strings.Builder, tgt target.Target) {
	if len(tgt.Epilogue) == 0 {
		return
	}
	fmt.Fprintf(b, "\t// Every return in the body above was rewritten to branch here.\n")
	for _, line := range tgt.Epilogue {
		fmt.Fprintf(b, "\t%s\n", line)
	}
}

// emitTrampoline emits a kernel as a framed caller plus a frameless body.
//
// The s390x ELF ABI puts the register save area at the *caller's* stack
// pointer: every non-trivial kernel begins "stmg %r14, %r15, 112(%r15)",
// storing above its own SP into memory the caller promised. Go promises no
// such thing, so those bytes are the calling Go function's locals, and the
// symptom is a slice header with a length past its capacity panicking
// somewhere else entirely.
//
// Giving the kernel a Go frame puts the save area in the right place but
// breaks the return: the compiled body ends in its own branch to the link
// register and never reaches the epilogue that would pop the frame, so
// control returns to Go with the stack pointer still lowered. Appending an
// epilogue is not possible either — LLVM lays basic blocks out after the
// return instruction, so there is no position after the body that always
// executes.
//
// Splitting the two apart solves both at once:
//
//	TEXT ·kernel(SB), NOSPLIT, $168-40      // frame, so the save area is ours
//	    ...load arguments into C registers...
//	    BL   ·kernelBody(SB)
//	    RET                                 // Go's epilogue restores SP
//
//	TEXT ·kernelBody(SB), NOSPLIT|NOFRAME, $0-0
//	    ...compiled bytes, unchanged...
//
// The body's save-area writes now land in the trampoline's frame, and its
// branch to the link register returns to the trampoline rather than to Go,
// with the stack pointer exactly as the body found it. Go's own epilogue then
// runs. The cost is one branch-and-link per call, against a kernel that is
// about to walk a whole slice.
//
// Go stores the link register at 0(SP) and puts locals above it, while the
// save area's occupied slots start at offset 48, so the two do not overlap.
func emitTrampoline(b *strings.Builder, k spec.Kernel, fn *objfile.Func,
	instrs []Instr, tgt target.Target, pools *poolSet, frame Frame) error {

	body := k.GoName + "Body"

	fmt.Fprintf(b, "TEXT ·%s(SB), NOSPLIT, $%d-%d\n", k.GoName, tgt.SaveArea, frame.Size)
	// The frame is a register save area for the compiled body and holds no Go
	// pointers, which is what NO_LOCAL_POINTERS declares. Without it the
	// runtime cannot walk this frame and aborts with "missing stackmap" when a
	// stack copy happens to catch one.
	fmt.Fprintf(b, "\tNO_LOCAL_POINTERS\n")
	prologue, err := prologueFor(k, frame, tgt)
	if err != nil {
		return err
	}
	for _, line := range prologue {
		fmt.Fprintf(b, "\t%s\n", line)
	}
	fmt.Fprintf(b, "\tBL ·%s(SB)\n", body)
	fmt.Fprintf(b, "\tRET\n\n")

	fmt.Fprintf(b, "// %s is the compiled kernel, called by the trampoline above so that\n", body)
	fmt.Fprintf(b, "// the register save area it writes belongs to the trampoline's frame.\n")
	fmt.Fprintf(b, "TEXT ·%s(SB), NOSPLIT|NOFRAME, $0-0\n", body)
	if err := emitRelocated(b, fn, instrs, tgt, pools, k.GoName); err != nil {
		return err
	}
	emitEpilogue(b, tgt)
	b.WriteString("\tRET\n\n")
	return nil
}

// emitBody writes the instruction bytes using the widest data directive the
// target's assembler accepts.
//
// Two details are easy to get wrong and neither fails loudly. The directives
// available differ per architecture — Go's s390x assembler has no QUAD, its
// ppc64le assembler has no BYTE — and the byte order differs too: WORD
// $0x11223344 places 11 22 33 44 in memory on big-endian s390x and 44 33 22 11
// everywhere else here. Packing the wrong way round produces a body of
// perfectly valid, entirely wrong instructions.
func emitBody(b *strings.Builder, code []byte, tgt target.Target) error {
	dirs := tgt.Directives
	if len(dirs) == 0 {
		dirs = []target.Directive{{Name: "WORD", Width: 4}}
	}
	for i := 0; i < len(code); {
		d, ok := widestFitting(dirs, len(code)-i)
		if !ok {
			return fmt.Errorf("emit: %d trailing byte(s) but %s has no directive "+
				"narrower than %d bytes", len(code)-i, tgt.Arch, dirs[len(dirs)-1].Width)
		}
		fmt.Fprintf(b, "\t%s $0x%0*x\n", d.Name, d.Width*2, pack(code[i:i+d.Width], tgt.BigEndian))
		i += d.Width
	}
	return nil
}

// widestFitting returns the widest directive that fits in the bytes remaining.
func widestFitting(dirs []target.Directive, remaining int) (target.Directive, bool) {
	for _, d := range dirs {
		if d.Width <= remaining {
			return d, true
		}
	}
	return target.Directive{}, false
}

// pack assembles bytes into the integer a data directive will re-emit as those
// same bytes, in the target's byte order.
func pack(bs []byte, bigEndian bool) uint64 {
	var v uint64
	if bigEndian {
		for _, c := range bs {
			v = v<<8 | uint64(c)
		}
		return v
	}
	for i := len(bs) - 1; i >= 0; i-- {
		v = v<<8 | uint64(bs[i])
	}
	return v
}

// emitRelocated writes a function body, resolving any reference out of it.
//
// The common case is that there is none and the whole body goes out as raw
// bytes. Where a relocation exists it is one of two kinds:
//
//   - self-relative, pointing back inside this same function. The field
//     already holds the right displacement and the body moves as a unit, so
//     nothing needs doing. riscv64 branches are like this.
//   - a constant-pool reference, which resolvePool handles by appending a copy
//     of the pool to the body and patching the displacement in place. Nothing
//     changes length, so every branch stays valid.
func emitRelocated(b *strings.Builder, fn *objfile.Func, instrs []Instr,
	tgt target.Target, pools *poolSet, goName string) error {

	needsWork := false
	for _, r := range fn.Relocs {
		if !isSelfRelative(r.TypeName) {
			needsWork = true
			break
		}
	}
	if !needsWork {
		code, err := retargetReturns(fn.Code, tgt)
		if err != nil {
			return fmt.Errorf("emit: %s (%s): %w", goName, tgt, err)
		}
		return emitBody(b, code, tgt)
	}

	var code []byte
	var err error
	var refs []poolInstr
	var sym string
	if tgt.Arch == target.PPC64LE {
		// ppc64le returns its pool separately rather than appended, because r2
		// points at the pool symbol and the offsets are from its base; see
		// constpool_power.go.
		var pool []byte
		if code, pool, err = resolvePoolPPC64(fn); err != nil {
			return fmt.Errorf("emit: %s (%s): %w", goName, tgt, err)
		}
		if len(pool) > 0 {
			sym := pools.add(goName+"_pool", pool)
			fmt.Fprintf(b, "\t// The constants live in %s<>(SB) and are reached through\n", sym)
			fmt.Fprintf(b, "\t// R2. clang computed that from r12 and a TOC which does not\n")
			fmt.Fprintf(b, "\t// exist here, so its two global-entry instructions are nops.\n")
			fmt.Fprintf(b, "\tMOVD\t$%s<>(SB), R2\n", sym)
		}
	} else if tgt.Arch == target.AMD64 && needsRespell(fn, instrs) {
		// At least one pool read is a legacy SSE instruction that cannot be
		// made to tolerate an unaligned address. Those read a separate RODATA
		// symbol and are written out as mnemonics; any others in the same
		// kernel keep the appended-pool treatment, which already works.
		var pool []byte
		if refs, pool, err = respellSSE2(fn, instrs, fn.Code, goName+"_pool"); err != nil {
			return fmt.Errorf("emit: %s (%s): %w", goName, tgt, err)
		}
		if code, err = resolvePoolExcept(fn, instrs, tgt, refs); err != nil {
			return fmt.Errorf("emit: %s (%s): %w", goName, tgt, err)
		}
		if len(pool) > 0 {
			sym = pools.add(goName+"_pool", pool)
			for i := range refs {
				refs[i].line = strings.Replace(refs[i].line, goName+"_pool<>", sym+"<>", 1)
			}
		}
	} else if code, err = resolvePool(fn, instrs, tgt); err != nil {
		return fmt.Errorf("emit: %s (%s): %w", goName, tgt, err)
	}
	// After the pool, not before: resolvePool appends data past the last
	// instruction, and a return retargeted to the end of the body would then
	// branch into it. Nothing needs both today — ppc64le is the only target
	// with an epilogue and it has no pool rewriter — but the order is the one
	// that stays correct if that changes.
	if code, err = retargetReturns(code, tgt); err != nil {
		return fmt.Errorf("emit: %s (%s): %w", goName, tgt, err)
	}
	if len(refs) > 0 {
		fmt.Fprintf(b, "\t// %s<>(SB) holds the constants this kernel reads with a legacy\n", sym)
		fmt.Fprintf(b, "\t// SSE instruction, which requires a 16-byte-aligned operand. A\n")
		fmt.Fprintf(b, "\t// separate RODATA symbol is aligned by the linker; bytes inside a\n")
		fmt.Fprintf(b, "\t// TEXT symbol are not. Those reads are the mnemonics below, each\n")
		fmt.Fprintf(b, "\t// exactly as long as the encoding it replaces so every branch\n")
		fmt.Fprintf(b, "\t// displacement in the body stays correct.\n")
		return emitBodyRespelled(b, code, refs, tgt)
	}
	fmt.Fprintf(b, "\t// Constant pool appended below the body; the displacements\n")
	fmt.Fprintf(b, "\t// above were patched to reach it and the aligned loads made\n")
	fmt.Fprintf(b, "\t// unaligned, since nothing promises alignment inside a TEXT.\n")
	return emitBody(b, code, tgt)
}

// hasOutOfFuncReloc reports whether a function refers to anything outside
// itself, which is what decides whether a pool rewrite is needed at all.
func hasOutOfFuncReloc(fn *objfile.Func) bool {
	for _, r := range fn.Relocs {
		if !isSelfRelative(r.TypeName) {
			return true
		}
	}
	return false
}

// CanLift reports whether a function's references out of itself can be
// resolved on this target, and why not if they cannot.
//
// The generator asks before emitting so an unsupported kernel is dropped and
// the portable implementation kept, rather than failing the whole target.
// amd64 resolves a reference as a single RIP-relative displacement; arm64
// turns the page-relative pair into a byte-relative one, which is what
// constpool_arm64.go is about. The remaining targets have no rewriter yet and
// keep the portable implementation for any kernel that needs a pool.
func CanLift(fn *objfile.Func, instrs []Instr, tgt target.Target) (bool, string) {
	switch tgt.Arch {
	case target.ARM64:
		return canLiftARM64(fn)
	case target.S390X:
		return canLiftS390X(fn)
	case target.LOONG64:
		return canLiftLoong64(fn)
	case target.RISCV64:
		return canLiftRISCV64(fn)
	case target.PPC64LE:
		// Two separate conditions on this target and both must hold. The
		// returns have to be retargetable so the r0-restoring epilogue always
		// runs (see returns_power.go), and any constant pool has to be one the
		// TOC rewrite can repoint (see constpool_power.go).
		if ok, why := canRetargetPPC64(fn.Code); !ok {
			return false, why
		}
		if hasOutOfFuncReloc(fn) {
			return canLiftPPC64(fn)
		}
	}
	for _, r := range fn.Relocs {
		if isSelfRelative(r.TypeName) {
			continue
		}
		if tgt.Arch != target.AMD64 {
			return false, "needs a constant pool, which is a high/low instruction pair on " +
				string(tgt.Arch)
		}
		if len(r.Target) == 0 {
			return false, "references " + r.Sym + ", which is not a constant pool"
		}
		// A legacy SSE arithmetic instruction with a memory operand requires
		// 16-byte alignment and has no unaligned form to switch to, so the
		// pool cannot simply be appended to the body. VEX and EVEX encodings
		// have no such requirement, which is why this only bites the baseline
		// tier.
		//
		// Such a reference is not fatal any more: it can read a separate
		// RODATA symbol instead, which the linker does align, with the one
		// instruction written out as a Plan 9 mnemonic of exactly the same
		// length. constpool_sse2.go does that, and refuses anything whose
		// encoding it has not verified — so the check here is now "can it be
		// patched OR re-spelled", and a kernel is still dropped when neither
		// works.
		if in, ok := instrAt(instrs, r.Off); ok {
			if err := checkPatchable(in); err != nil {
				if _, ok := respellable[in.Mnemonic]; !ok {
					return false, err.Error()
				}
			}
		}
	}
	return true, ""
}

// checkPatchable reports whether an instruction reading a constant pool can be
// made to tolerate an unaligned address.
//
// There is a tempting fix for the ones that cannot: pad the appended pool to a
// 16-byte offset within the function, and rely on the linker aligning every
// text symbol — 32 bytes on amd64, per cmd/link/internal/amd64.funcAlign — to
// make that a 16-byte-aligned address. Do not. That alignment is not a
// guarantee: cmd/link takes a -funcalign flag, so a consumer building with
// -ldflags=-funcalign=8 would get a SIGSEGV out of this library and no
// plausible way to trace it back. Dropping the kernel and keeping the portable
// path costs a few percent on the baseline tier, which is the tier a machine
// only reaches if it predates AVX2.
func checkPatchable(in Instr) error {
	switch {
	case alignedLoads[in.Mnemonic], alignedInteger[in.Mnemonic]:
		return nil // one byte to patch
	case strings.HasPrefix(in.Mnemonic, "v"):
		return nil // VEX and EVEX impose no alignment
	case unalignedLoads[in.Mnemonic]:
		return nil
	}
	return fmt.Errorf("reads a constant pool with %q, a legacy SSE instruction that "+
		"requires 16-byte alignment and has no same-length unaligned form", in.Mnemonic)
}

// isSelfRelative reports whether a relocation targets a location inside the
// same function, so that copying the bytes preserves it.
func isSelfRelative(typeName string) bool {
	switch typeName {
	case "R_RISCV_BRANCH", "R_RISCV_JAL", "R_RISCV_RVC_BRANCH", "R_RISCV_RVC_JUMP":
		return true
	case "R_AARCH64_JUMP26", "R_AARCH64_CONDBR19", "R_AARCH64_TSTBR14":
		return true
	// NOT R_LARCH_B16, B21 or B26, and the reason is worth stating because
	// the RISC-V and AArch64 entries above make the opposite look obvious.
	//
	// On those targets the assembler resolves an internal branch and the
	// relocation is informational, left for the linker's relaxation pass. On
	// LoongArch it does not: clang emits the branch with a displacement of
	// ZERO and expects the linker to fill it in.
	//
	//	73fc: blez $a2, 0 <simd_widen_u8_u16>
	//	740c: b    0 <simd_widen_u8_u16+0x10>      <- branches to itself
	//
	// Copying those bytes verbatim produces a branch to itself. Treating them
	// as self-relative, as this function briefly did, put 23 loong64 kernels
	// back in the build and hung the emulated lane in an infinite loop inside
	// simd_widen_u8_u16. The "references .L0, which is not a constant pool"
	// rejection those kernels get instead is not a gap to route around — it is
	// this generator correctly declining to copy code it cannot relocate.
	//
	// Making them work needs the displacement computed and patched into the
	// instruction, per branch format, the way the constant-pool code already
	// patches PCALA pairs. Until then they keep the portable path.
	case "R_RISCV_RELAX":
		// Not a fixup: a marker telling the linker a sequence could be
		// shortened. Nothing links this object, so it changes no bytes.
		return true
	case "R_LARCH_RELAX", "R_LARCH_ALIGN":
		// The same, for LoongArch. ALIGN marks padding the linker is allowed
		// to shrink when relaxation moves code; leaving it alone keeps exactly
		// what the assembler emitted, which is already correct.
		//
		// These carry no symbol at all, so they were reported as "references
		// , which is not a constant pool" — a message with an empty name in
		// the middle of it, which is what a relocation that names nothing
		// looks like when it is assumed to name something.
		return true
	}
	return false
}

// ErrTooManyArgs reports a kernel whose C signature needs more argument
// registers than the target has. It is a capability limit like any other, so
// the caller drops the kernel rather than failing the whole target.
var ErrTooManyArgs = errors.New("kernel needs more argument registers than the target has")

// prologueFor builds the instructions that move Go's stack-passed arguments
// into the registers the compiled C body expects.
//
// This is the whole ABI bridge. Go's ABI0 puts every argument in the caller's
// frame at an FP-relative offset; the System V and AAPCS conventions the C
// code was compiled against put them in registers.
func prologueFor(k spec.Kernel, frame Frame, tgt target.Target) ([]string, error) {
	var (
		lines    []string
		nextInt  int
		nextFlt  int
		widest   int
		comments []string
	)
	for i, ca := range k.CArgs {
		p, _ := k.Param(ca.From)

		var (
			slot string
			off  int
			typ  spec.Type
		)
		if ca.Part == spec.ResultAddr || ca.Part == spec.ResultAddr2 {
			if tgt.AddrOf == "" {
				return nil, fmt.Errorf("emit: %s: no address-of mnemonic for %s", k.GoName, tgt.Arch)
			}
			if nextInt >= len(tgt.IntArgs) {
				return nil, fmt.Errorf("emit: %s: no register left for the result pointer", k.GoName)
			}
			reg := tgt.IntArgs[nextInt]
			nextInt++
			// The name has to be the one in the generated Go declaration, not
			// a fixed "ret": go vet's asmdecl matches assembly operands to
			// declared parameter names, and a pair of results is declared with
			// names because Go requires all-or-none. Single-result kernels
			// carry the name "ret" in the manifest, so this is uniform.
			name, off := k.Result.Name, frame.ResultOff
			if ca.Part == spec.ResultAddr2 {
				name, off = k.Result2.Name, frame.ResultOff2
			}
			operand := fmt.Sprintf("%s+%d(FP)", name, off)
			if tgt.Arch != target.AMD64 {
				// RISC-style assemblers spell "address of" as a move of a
				// $-prefixed operand.
				operand = "$" + operand
			}
			lines = append(lines, fmt.Sprintf("%s %s, %s", tgt.AddrOf, operand, reg))
			continue
		}
		switch ca.Part {
		case spec.Base:
			slot, off, typ = ca.From+"_base", frame.Offsets[ca.From+"_base"], spec.I64
		case spec.Len:
			slot, off, typ = ca.From+"_len", frame.Offsets[ca.From+"_len"], spec.Int
		case spec.Cap:
			slot, off, typ = ca.From+"_cap", frame.Offsets[ca.From+"_cap"], spec.Int
		case spec.Value:
			slot, off, typ = ca.From, frame.Offsets[ca.From], p.Type
		}

		var reg string
		if typ.IsFloat() {
			if nextFlt >= len(tgt.FloatArgs) {
				return nil, fmt.Errorf("emit: %s: more than %d floating-point C arguments on %s",
					k.GoName, len(tgt.FloatArgs), tgt)
			}
			reg = tgt.FloatArgs[nextFlt]
			nextFlt++
			// On a target with a parallel parameter save area the float also
			// owns an integer slot, so every later integer argument shifts up
			// one register. See target.FloatArgsUseIntSlot.
			if tgt.FloatArgsUseIntSlot {
				nextInt++
			}
		} else {
			if nextInt >= len(tgt.IntArgs) {
				// Arguments beyond the register set would have to be pushed
				// onto a C stack frame, which this generator does not build.
				//
				// This is a capability of the target, not a mistake: System V
				// passes six integer arguments in registers and the zSeries
				// ABI five, so a kernel that needs six is simply unavailable
				// on s390x. ErrTooManyArgs lets the caller drop the kernel and
				// keep the portable path rather than failing the target.
				return nil, fmt.Errorf("%w: emit: %s: more than %d integer C arguments on %s; "+
					"simplify the kernel signature", ErrTooManyArgs, k.GoName, len(tgt.IntArgs), tgt)
			}
			reg = tgt.IntArgs[nextInt]
			nextInt++
		}

		mov, err := loadInstr(typ, tgt)
		if err != nil {
			return nil, fmt.Errorf("emit: %s argument %d: %w", k.GoName, i, err)
		}
		operand := fmt.Sprintf("%s+%d(FP)", slot, off)
		lines = append(lines, fmt.Sprintf("%s %s, %s", mov, operand, reg))
		if n := len(mov) + len(operand); n > widest {
			widest = n
		}
		comments = append(comments, fmt.Sprintf("C arg %d", i))
	}
	return lines, nil
}

// loadInstr is the Plan 9 mnemonic that moves a value of the given type
// between the argument frame and a register, taken from the target's table.
func loadInstr(t spec.Type, tgt target.Target) (string, error) {
	var m string
	switch t {
	case spec.F32:
		m = tgt.MovFloat32
	case spec.F64:
		m = tgt.MovFloat64
	case spec.I32:
		m = tgt.MovInt32
	case spec.U8, spec.B:
		m = tgt.MovByte
	// The narrow integers widen into a full register, because their C
	// parameter is a 64-bit integer; see target.Target.MovInt8 for why it has
	// to be. Signed sign-extends and unsigned zero-extends, so that the value
	// the kernel casts back down is the one the caller passed.
	case spec.I8:
		m = tgt.MovInt8
	case spec.I16:
		m = tgt.MovInt16
	case spec.U16:
		m = tgt.MovUint16
	case spec.U32:
		m = tgt.MovUint32
	default:
		m = tgt.MovPtr
	}
	if m == "" {
		return "", fmt.Errorf("no move mnemonic for %s on %s", t.GoString(), tgt.Arch)
	}
	return m, nil
}

// storeResult writes the C return register back into the Go result slot.
func storeResult(r spec.Param, off int, tgt target.Target) (string, error) {
	reg := tgt.IntResult
	if r.Type.IsFloat() {
		reg = tgt.FloatResult
	}
	mov, err := loadInstr(r.Type, tgt)
	if err != nil {
		return "", err
	}
	// A byte-width store uses the plain mnemonic; the zero-extending form is
	// only meaningful when loading.
	if r.Type == spec.B || r.Type == spec.U8 {
		mov = "MOVB"
	}
	return fmt.Sprintf("%s %s, ret+%d(FP)", mov, reg, off), nil
}

// ---------- constant pools ----------

type poolSet struct {
	order []string
	data  map[string][]byte
}

func newPoolSet() *poolSet { return &poolSet{data: map[string][]byte{}} }

// add records a constant pool and returns the Go symbol name for it.
//
// Two kernels compiled from one translation unit often share a pool, so the
// same name is reused rather than emitting the bytes twice.
func (p *poolSet) add(elfName string, data []byte) string {
	name := goSymName(elfName)
	if _, seen := p.data[name]; !seen {
		p.data[name] = data
		p.order = append(p.order, name)
	}
	return name
}

// goSymName turns an ELF section or symbol name into a Go identifier.
func goSymName(s string) string {
	if s == "" {
		s = "const"
	}
	var b strings.Builder
	b.WriteString("simdconst_")
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

func (p *poolSet) render() string {
	if len(p.order) == 0 {
		return ""
	}
	var b strings.Builder
	for _, name := range p.order {
		d := p.data[name]
		// Every byte the GLOBL declares must be covered by a DATA directive.
		// The assembler zero-fills whatever is left, so a pool whose length is
		// not a multiple of eight silently loses its tail rather than failing
		// to build: the last 4-byte constant reads as 0.0f, and only the
		// kernel that happens to use it is wrong. simd_quantize_u8 read the
		// upper clamp that way and clamped its whole scalar tail to zero,
		// which showed up as one wrong element in 17 on ppc64le alone.
		//
		// So step down through the directive widths Plan 9 has rather than
		// assuming eight divides the length. 4 is the remainder that occurs
		// in practice — a .rodata.cst4 section ending an odd number of
		// 4-byte constants — but 2 and 1 cost nothing to handle.
		for i := 0; i < len(d); {
			w := 8
			for w > len(d)-i {
				w /= 2
			}
			var q uint64
			for j := w - 1; j >= 0; j-- {
				q = q<<8 | uint64(d[i+j])
			}
			fmt.Fprintf(&b, "DATA %s<>+0x%03x(SB)/%d, $0x%0*x\n", name, i, w, w*2, q)
			i += w
		}
		fmt.Fprintf(&b, "GLOBL %s<>(SB), RODATA|NOPTR, $%d\n\n", name, len(d))
	}
	return b.String()
}

// ---------- Go declarations ----------

// Stub renders the Go file declaring the kernels for one target.
//
// The result is passed through go/format, so generated code is gofmt-clean on
// the way out rather than depending on someone remembering to run gofmt over
// it afterwards. A repository-wide format check is a CI gate here, and
// generated files should never be the reason it fails.
func Stub(kernels []spec.Kernel, tgt target.Target, pkg string, prov Provenance) string {
	src := stubSource(kernels, tgt, pkg, prov)
	formatted, err := format.Source([]byte(src))
	if err != nil {
		// Emitting the unformatted source is more useful than failing: the
		// compiler will point at whatever is malformed.
		return src
	}
	return string(formatted)
}

func stubSource(kernels []spec.Kernel, tgt target.Target, pkg string, prov Provenance) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by simdgen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Source: %s\n", prov.Source)
	fmt.Fprintf(&b, "// Target: %s\n\n", tgt)
	fmt.Fprintf(&b, "//go:build %s\n\n", tgt.BuildTag())
	fmt.Fprintf(&b, "package %s\n\nimport \"runtime\"\n\n", pkg)
	b.WriteString(archAssertion(tgt))

	for _, k := range kernels {
		if k.Doc != "" {
			for _, line := range strings.Split(k.Doc, "\n") {
				fmt.Fprintf(&b, "// %s\n", line)
			}
		}
		// //go:noescape is not an optimisation here, it is required. Without
		// it, escape analysis has to assume the assembly leaks its pointer
		// arguments, and every slice handed to a kernel is forced onto the
		// heap. It is an unchecked promise: these kernels only read and write
		// through the pointers they are given, and store none of them.
		if k.Doc != "" {
			b.WriteString("//\n")
		}
		fmt.Fprintf(&b, "//go:noescape\nfunc %s(%s)%s\n\n", k.GoName, goParams(k), goResult(k))
	}
	return b.String()
}

func goParams(k spec.Kernel) string {
	parts := make([]string, len(k.Params))
	for i, p := range k.Params {
		parts[i] = p.Name + " " + p.Type.GoString()
	}
	return strings.Join(parts, ", ")
}

func goResult(k spec.Kernel) string {
	if k.Result == nil {
		return ""
	}
	if k.Result2 == nil {
		return " " + k.Result.Type.GoString()
	}
	// Named, because Go requires either all results named or none, and the
	// declaration this feeds is what `go vet`'s asmdecl checks against the
	// frame layout above.
	return fmt.Sprintf(" (%s %s, %s %s)",
		k.Result.Name, k.Result.Type.GoString(),
		k.Result2.Name, k.Result2.Type.GoString())
}

// Backend renders the Go file that registers the generated kernels with the
// dispatcher.
//
// Each tier starts from the portable reference and overrides only the kernels
// it actually has, which is what lets kernels land a few at a time without
// ever leaving a nil function in the table.
//
// Every kernel is installed behind a threshold guard. A Go-to-assembly call
// costs a fixed ~1.4ns and can never be inlined, so below some element count
// the call is more expensive than the arithmetic it replaces — viterin/vek
// loses to a plain Go loop at n=4 for exactly this reason, and has an open
// issue about it. The guard sends small inputs to the reference instead.
func Backend(kernels []spec.Kernel, tgt target.Target, pkg string, prov Provenance) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by simdgen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Source: %s\n// Target: %s\n\n", prov.Source, tgt)
	fmt.Fprintf(&b, "//go:build %s\n\n", tgt.BuildTag())
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import (\n\t\"runtime\"\n\n\t%q\n\t%q\n)\n\n",
		"github.com/sebishogun/simd/internal/kernel",
		"github.com/sebishogun/simd/internal/ref")

	// The kernels arrive with their tier already in their names; only the
	// file-scope helpers need a suffix to stay distinct between tiers.
	b.WriteString(archAssertion(tgt))

	suffix := strings.ToUpper(tgt.Tier)

	// The guards are named functions rather than closures so the fast path is
	// a direct call to the assembly rather than an indirect one through a
	// captured variable.
	for _, k := range kernels {
		emitGuard(&b, k, suffix, string(tgt.Arch))
	}

	// Registration is a function the per-arch Sets aggregator calls, not an
	// init. An init would make every guard reachable in every binary that
	// imports this package, which is exactly the liveness the per-operation
	// dispatch tables exist to break; only the conformance machinery wants
	// whole sets, and it can ask for them.
	fmt.Fprintf(&b, "func register%s%s(s *kernel.Set) {\n",
		strings.ToUpper(prov.Stem[:1])+prov.Stem[1:], suffix)
	for _, k := range kernels {
		fmt.Fprintf(&b, "\ts.%s.%s = %s\n", k.Group, k.Field, guardName(k, suffix))
	}
	fmt.Fprintf(&b, "}\n")

	if formatted, err := format.Source([]byte(b.String())); err == nil {
		return string(formatted)
	}
	return b.String()
}

// archAssertion emits a compile-time check that the file is being built for
// the architecture its assembly targets.
//
// The build constraint and the filename suffix already restrict it, and both
// are enforced by the toolchain. This is a third, independent guard against a
// generator bug that emitted the wrong tag: runtime.GOARCH is a constant, so
// a mismatch makes the map literal have two `false` keys, which the compiler
// rejects outright. The alternative failure mode is a binary full of
// instructions the CPU cannot decode.
func archAssertion(tgt target.Target) string {
	return fmt.Sprintf(`// Compile-time check that this file is only ever built for %[1]s. The build
// constraint above and the _%[1]s filename suffix should both already ensure
// it; if either were wrong this map literal would have a duplicate false key,
// which is a compile error rather than a SIGILL on someone else's machine.
var _ = map[bool]struct{}{false: {}, runtime.GOARCH == %[1]q: {}}

`, tgt.Arch)
}

// guardName is the exported threshold wrapper for a kernel. Exported, not
// a style choice: the root package's dispatch tables name these directly in
// static composite literals, which is what lets the linker drop every
// operation a program never calls -- an unexported guard would need the
// registry, the registry needs init, and anything reachable from init is
// alive in every binary forever.
func guardName(k spec.Kernel, _ string) string {
	return strings.ToUpper(k.GoName[:1]) + k.GoName[1:]
}

// emitGuard writes the threshold wrapper for one kernel.
func emitGuard(b *strings.Builder, k spec.Kernel, suffix, arch string) {
	params := goParams(k)
	result := goResult(k)

	// The length that decides, and that the kernel is bounded by.
	//
	// The C kernel takes exactly one length and trusts it for every pointer it
	// was handed, while the portable implementations all clamp to the shortest
	// slice — so handing the kernel len(dst) when a caller passed a shorter
	// source is a read past the end. Clamping here keeps the two paths agreeing
	// and costs a few compares against a call that is already ~1.4ns.
	//
	// Only the length parameter is resliced. The others contribute their length
	// to the minimum but are passed whole, because the kernel reads nothing
	// from them but their base pointer, and reslicing does not move that.
	lenExpr, clamped := "0", ""
	if name, ok := k.LenParam(); ok {
		lenExpr = "len(" + name + ")"
		if others := boundingSlices(k, name); len(others) > 0 && countLens(k) == 1 &&
			!k.UnclampedDst {
			lenExpr, clamped = "n", name
		}
	} else if len(k.Params) > 0 {
		lenExpr = "len(" + k.Params[0].Name + ")"
	}

	fmt.Fprintf(b, "func %s(%s)%s {\n", guardName(k, suffix), params, result)
	if clamped != "" {
		args := append([]string{"len(" + clamped + ")"}, boundingSlices(k, clamped)...)
		fmt.Fprintf(b, "\tn := min(%s)\n", strings.Join(args, ", "))
	}
	fmt.Fprintf(b, "\tif %s < %d%s {\n", lenExpr, k.ThresholdFor(arch), extraRefCond(k))
	// Call the portable implementation directly rather than through the
	// kernel set. Going via the function pointer costs an indirect call that a
	// purego build never pays, which made the accelerated build slower than
	// the portable one on short slices.
	if k.Result != nil {
		fmt.Fprintf(b, "\t\treturn ref.%s(%s)\n", k.RefFunc, argNames(k))
	} else {
		fmt.Fprintf(b, "\t\tref.%s(%s)\n\t\treturn\n", k.RefFunc, argNames(k))
	}
	fmt.Fprintf(b, "\t}\n")
	call := k.GoName + "(" + callArgs(k, clamped) + ")"
	if k.Result != nil {
		fmt.Fprintf(b, "\treturn %s\n}\n\n", call)
	} else {
		fmt.Fprintf(b, "\t%s\n}\n\n", call)
	}
}

// callArgs names the arguments to the assembly kernel, reslicing the one whose
// length it is bounded by so the length it reads is the clamped one.
func callArgs(k spec.Kernel, clamped string) string {
	names := make([]string, len(k.Params))
	for i, p := range k.Params {
		names[i] = p.Name
		if p.Name == clamped {
			names[i] = p.Name + "[:n:n]"
		}
	}
	return strings.Join(names, ", ")
}

// boundingSlices returns len() expressions for every slice the kernel reads or
// writes other than the one supplying the length, in declaration order.
func boundingSlices(k spec.Kernel, lenParam string) []string {
	var out []string
	seen := map[string]bool{lenParam: true}
	for _, a := range k.CArgs {
		if a.Part != spec.Base || seen[a.From] {
			continue
		}
		seen[a.From] = true
		out = append(out, "len("+a.From+")")
	}
	return out
}

// countLens reports how many lengths the kernel takes. A kernel taking two —
// Diff, whose output is one element shorter than its input — reconciles them
// itself, so the guard must not clamp them together.
func countLens(k spec.Kernel) int {
	n := 0
	for _, a := range k.CArgs {
		if a.Part == spec.Len {
			n++
		}
	}
	return n
}

// extraRefCond renders the kernel's RefWhen condition as an additional reason
// to take the portable path.
func extraRefCond(k spec.Kernel) string {
	if k.RefWhen == "" {
		return ""
	}
	return " || " + k.RefWhen
}

func argNames(k spec.Kernel) string {
	names := make([]string, len(k.Params))
	for i, p := range k.Params {
		names[i] = p.Name
	}
	return strings.Join(names, ", ")
}

// LayoutPrologue builds a kernel's argument prologue and reports whether it
// can be built at all, so the generator can drop a kernel whose signature does
// not fit the target's argument registers.
func LayoutPrologue(k spec.Kernel, tgt target.Target) ([]string, error) {
	return prologueFor(k, LayoutFrame(k), tgt)
}
