// Command thresholds generates the per-architecture kernel threshold tables in
// the root package, from the same manifest the guards are generated from.
//
// A kernel's guard sends inputs below a length to the portable reference
// implementation, and that length was knowable only by reading generated
// assembly guards. Callers in other repositories were deriving their own
// constants from memory instead -- simdjson's kernelScanMin was 32 because
// simd_json_copy_run's threshold had been lowered to 32, while
// simd_json_copy_valid's was still 64, and every call between the two numbers
// ran a Go byte loop while looking like a kernel call. One constant, written
// down twice, in two repositories.
//
// This makes the number askable: simd.KernelThreshold("JSONCopyRun") on the
// running architecture. It needs no clang and touches no kernels, so it can be
// run alone; `make codegen` runs it too.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	"github.com/sebishogun/simd/tools/simdgen/kernels"
)

var goarches = []string{"amd64", "arm64", "riscv64", "s390x", "ppc64le", "loong64"}

func main() {
	root := ".."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	// Field -> per-arch threshold. Field is the dispatch-struct name, which is
	// also how the exported API names the operation.
	type entry struct {
		field string
		by    map[string]int
	}
	var entries []entry
	seen := map[string]bool{}
	for _, src := range kernels.All {
		for _, k := range src.Kernels {
			if k.Field == "" || seen[k.Field] {
				continue
			}
			seen[k.Field] = true
			e := entry{field: k.Field, by: map[string]int{}}
			for _, a := range goarches {
				e.by[a] = k.ThresholdFor(a)
			}
			entries = append(entries, e)
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].field < entries[j].field })

	for _, arch := range goarches {
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by simdgen/thresholds. DO NOT EDIT.\n\n")
		fmt.Fprintf(&b, "package simd\n\n")
		fmt.Fprintf(&b, "// kernelThresholds on %s. See KernelThreshold.\n", arch)
		fmt.Fprintf(&b, "var kernelThresholds = map[string]int{\n")
		for _, e := range entries {
			fmt.Fprintf(&b, "\t%q: %d,\n", e.field, e.by[arch])
		}
		fmt.Fprintf(&b, "}\n")
		src, err := format.Source(b.Bytes())
		if err != nil {
			fmt.Fprintln(os.Stderr, "thresholds:", err)
			os.Exit(1)
		}
		path := filepath.Join(root, fmt.Sprintf("kernel_thresholds_%s.go", arch))
		if err := os.WriteFile(path, src, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "thresholds:", err)
			os.Exit(1)
		}
	}
	// The exact goName map, for the drift test: guard function names are
	// goName+tier, and the goName-to-Field relation is arbitrary (sumsq under
	// SumSquares), so the test gets exact keys rather than heuristics. One
	// file, all architectures, no build tags -- it is data for a test.
	var tb bytes.Buffer
	fmt.Fprintf(&tb, "// Code generated by simdgen/thresholds. DO NOT EDIT.\n\n")
	fmt.Fprintf(&tb, "package thresholds\n\n")
	fmt.Fprintf(&tb, "// gonameThresholds is every kernel's guard threshold by architecture and\n")
	fmt.Fprintf(&tb, "// generated Go name, from the manifest. TestGuardsMatchTables compares the\n")
	fmt.Fprintf(&tb, "// generated guard code against it.\n")
	fmt.Fprintf(&tb, "var gonameThresholds = map[string]map[string]int{\n")
	type gn struct {
		name string
		by   map[string]int
	}
	var gns []gn
	gseen := map[string]bool{}
	for _, src := range kernels.All {
		for _, k := range src.Kernels {
			if k.GoName == "" || gseen[k.GoName] {
				continue
			}
			gseen[k.GoName] = true
			e := gn{name: k.GoName, by: map[string]int{}}
			for _, a := range goarches {
				e.by[a] = k.ThresholdFor(a)
			}
			gns = append(gns, e)
		}
	}
	sort.Slice(gns, func(i, j int) bool { return gns[i].name < gns[j].name })
	for _, arch := range goarches {
		fmt.Fprintf(&tb, "\t%q: {\n", arch)
		for _, e := range gns {
			fmt.Fprintf(&tb, "\t\t%q: %d,\n", e.name, e.by[arch])
		}
		fmt.Fprintf(&tb, "\t},\n")
	}
	fmt.Fprintf(&tb, "}\n")
	tsrc, err := format.Source(tb.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "thresholds:", err)
		os.Exit(1)
	}
	tpath := filepath.Join(root, "internal", "tests", "thresholds", "goname_thresholds_gen.go")
	if err := os.WriteFile(tpath, tsrc, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "thresholds:", err)
		os.Exit(1)
	}
	fmt.Printf("thresholds: %d operations, %d go names, %d architectures\n",
		len(entries), len(gns), len(goarches))
}
